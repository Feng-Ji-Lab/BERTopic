render <- function(name, draw, width = 9, height = 4.8) {
  png(file.path(output, paste0(name, ".png")), width = width * 200, height = height * 200, res = 200)
  draw(); dev.off()
  pdf(file.path(output, paste0(name, ".pdf")), width = width, height = height)
  draw(); dev.off()
}
measure_plot <- function(column, xlabel, title) {
  values <- split(runs[[column]], factor(runs$path, levels = c("Python", "R")))
  plot(range(c(0, unlist(values))) * c(1, 1.12), c(0.5, 2.5), type = "n",
       xlab = xlabel, ylab = "", yaxt = "n", main = title, bty = "n")
  axis(2, at = 1:2, labels = names(values), las = 1)
  colors <- c("#3178A5", "#C45D32")
  for (i in seq_along(values)) {
    x <- values[[i]]; q <- quantile(x, c(.25, .5, .75))
    points(x, rep(i + .09, length(x)), pch = 1, col = colors[i])
    segments(q[1], i, q[3], i, lwd = 4, col = colors[i])
    points(q[2], i, pch = 19, cex = 1.3, col = colors[i])
  }
  mtext("Filled point: median; line: IQR; open points: all five runs", side = 1, line = 4.5, cex = .75)
}
render("runtime", function() {
  par(mfrow = c(1, 2), mar = c(6.5, 4, 3, 1))
  measure_plot("fit_seconds", "Seconds", "Controlled fitting")
  measure_plot("cold_seconds", "Seconds", "Fresh process")
})
render("peak_memory", function() {
  par(mar = c(6.5, 4, 3, 1))
  measure_plot("peak_rss_mib", "Peak RSS (MiB)", "Windows peak resident memory")
}, width = 7)
render("largest_topics", function() {
