# Regenerate manuscript-ready tables and plots from validated paired outputs.
options(stringsAsFactors = FALSE)
args <- commandArgs(trailingOnly = TRUE)
get_arg <- function(flag, default) {
  i <- match(flag, args)
  if (is.na(i) || i == length(args)) default else args[[i + 1L]]
}
results <- normalizePath(get_arg("--results", "benchmark/results"), winslash = "/", mustWork = TRUE)
output <- get_arg("--output", file.path(results, "artifacts"))
dir.create(output, recursive = TRUE, showWarnings = FALSE)
equivalence <- read.csv(file.path(results, "equivalence.csv"))
if (!all(unlist(equivalence[, grepl("equal", names(equivalence)), drop = FALSE]))) {
  stop("Refusing to export manuscript artifacts from a failed equivalence run")
}
runs <- read.csv(file.path(results, "runs.csv"))
summary <- read.csv(file.path(results, "summary.csv"))
info <- read.csv(file.path(results, "runs/r-01/topic_info.csv"))
terms <- read.csv(file.path(results, "runs/r-01/topic_terms.csv"))
topics <- scan(file.path(results, "runs/r-01/topics.csv"), what = integer(), quiet = TRUE)
probabilities <- as.matrix(read.csv(file.path(results, "runs/r-01/probabilities.csv"), header = FALSE))
valid_info <- info[info$Topic != -1, ]
top_info <- head(valid_info[order(-valid_info$Count), ], 8L)
top_info$Terms <- vapply(top_info$Topic, function(id) {
  paste(head(terms$Term[terms$Topic == id], 4L), collapse = ", ")
}, character(1))
write.csv(top_info[, c("Topic", "Count", "Terms")], file.path(output, "largest_topics.csv"), row.names = FALSE)
stat <- function(metric) summary[summary$metric == metric, c("median", "q1", "q3")]
format_stat <- function(metric, digits = 3L) {
  x <- unlist(stat(metric), use.names = FALSE)
  sprintf(paste0("%.", digits, "f [%.", digits, "f, %.", digits, "f]"), x[1], x[2], x[3])
}
facts <- data.frame(
  metric = c("documents", "non_outlier_topics", "topic_info_rows", "outliers", "outlier_percent",
             "term_keys", "probability_rows", "probability_columns", "pairs_passed",
             "max_term_weight_difference", "max_probability_difference"),
  value = c(length(topics), nrow(valid_info), nrow(info), sum(topics == -1L),
            100 * mean(topics == -1L), nrow(terms), nrow(probabilities), ncol(probabilities),
            nrow(equivalence), max(equivalence$max_term_weight_difference),
            max(equivalence$max_probability_difference))
)
write.csv(facts, file.path(output, "facts.csv"), row.names = FALSE)
latex_escape <- function(x) {
  for (s in c("_", "%", "&", "#", "$")) x <- gsub(s, paste0("\\", s), x, fixed = TRUE)
  x
}
